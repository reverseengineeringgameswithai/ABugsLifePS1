#!/usr/bin/env python3
"""Generate per-stage identity scenarios from the Phase-2 stage baseline.

Reads analysis/phase2_stage_baseline.json and emits, for every identity/bonus
anchor, a declarative ps1_scenario YAML asserting ONLY the fields the baseline
proved stable across the volatility window (the differential mask applied by
construction), plus a suite manifest. Scenarios anchor on the hash-pinned save
state over the pristine disc — the oracle rules' "narrow runtime anchor" form.

Usage: python3 tools/gen_stage_identity_scenarios.py
Run:   python3 tools/run_ps1_suite.py tools/scenarios/duckstation/stage_identity_suite.json
"""
from __future__ import annotations

import json
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
BASELINE = ROOT / "analysis" / "phase2_stage_baseline.json"
OUTDIR = ROOT / "tools" / "scenarios" / "duckstation"
PRISTINE_CUE = "Disney-Pixar A Bug's Life (v1.0).cue"

# memory-assertable snapshot fields: name -> (address, width)
FIELDS = {
    "scene_id": (0x80082504, "u32"),
    "player_x": (0x800A6500, "s32"),
    "player_y": (0x800A6504, "s32"),
    "player_z": (0x800A6508, "s32"),
    "player_floor": (0x800A6548, "s32"),
    "player_grounded": (0x800A6582, "u8"),
    "health": (0x800A7E2A, "s16"),
    "lives": (0x800A65A0, "u8"),
    "grain": (0x800A65A1, "u8"),
    "enemy_quota": (0x800A658E, "u8"),
    "equipped_berry": (0x800A6597, "u8"),
    "power_word": (0x800A6590, "u8"),
}


def main() -> int:
    doc = json.loads(BASELINE.read_text())
    generated = []
    for label, st in sorted(doc["stages"].items()):
        if st.get("role") not in ("identity", "identity_bonus") or "error" in st:
            continue
        anchor = st["anchor"]
        stable = set(st["stable_fields"])
        assertions = []
        for name in sorted(FIELDS):
            if name not in stable:
                continue  # volatile at this anchor -> excluded from the equality oracle
            addr, width = FIELDS[name]
            assertions.append({
                "id": f"{label}_{name}",
                "type": "memory", "address": addr, "width": width,
                "op": "eq", "expected": anchor[name],
                "description": f"pristine baseline value at this anchor (stable across "
                               f"{st['volatility_frames']} frames)",
            })
        scenario = {
            "schema_version": 1,
            "id": f"stage_identity_{label}",
            "description": f"Pristine identity oracle for {label}: hash-pinned save anchor "
                           "+ stable-field equality (generated by gen_stage_identity_scenarios.py "
                           "from analysis/phase2_stage_baseline.json — regenerate, don't hand-edit).",
            "target": {"disc": PRISTINE_CUE, "expected_serial": "SCUS-94288"},
            "launch": {"profile": "repro"},
            "anchor": {"type": "save_state", "path": st["save"],
                       "sha256": st["save_sha256"]},
            "phases": [{
                "id": "anchored",
                "trigger": {"type": "memory", "address": 0x80082504, "width": "u32",
                            "op": "eq", "value": anchor["scene_id"], "max_frames": 120,
                            "timeout_seconds": 120},
                "assertions": assertions,
            }],
        }
        path = OUTDIR / f"stage_identity_{label}.yaml"
        path.write_text(yaml.safe_dump(scenario, sort_keys=False, width=100))
        generated.append(str(path.relative_to(ROOT)))
        print(f"  {path.name}: {len(assertions)} stable-field assertions")
    suite = {
        "schema_version": 1,
        "id": "stage_identity_oracle",
        "description": "Per-stage pristine identity oracle (generated; Training + 15 "
                       "stages + 3 bonus-entry anchors).",
        "scenarios": generated,
    }
    suite_path = OUTDIR / "stage_identity_suite.json"
    suite_path.write_text(json.dumps(suite, indent=1) + "\n")
    print(f"[gen] {len(generated)} scenarios + {suite_path.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

#!/usr/bin/env python3
"""Byte-splat reconstruction build (decomp substrate — docs/SUBSTRATE.md).

Copies the owner's original SCUS_942.88 and replaces ONLY the functions listed
under `attempted` in config/segments.yml with bytes built from source at their
original VA — dispatched by extension: `.s` = asm path (asm/hand_written/,
as -> ld -> objcopy), `.c` = C path (src/main/, cpp/cc1 -> maspsx -> same tail,
c_toolchain block). Everything else is original bytes, so the build is exact by
construction; each attempted function proves only itself. Output:
build/substrate/SCUS_942.88.rebuilt (+ build_manifest.json, per-entry
`language`). Verify with tools/validate_build.py; per-function diffs with
tools/asmdiff.py.

Also emits build/substrate/census_symbols.inc (`.equ name, addr` for every
named census function) so hand-written sources can `jal` engine functions by
name: assemble picks it up via `.include "census_symbols.inc"`.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from substrate_common import (BUILD, HANDWRITTEN, ROOT, build_entry,  # noqa: E402
                              load_segments, original_exe, sha1, va_to_off)


def write_symbols_inc() -> Path:
    census = json.loads((ROOT / "analysis" / "functions.json").read_text())
    lines = ["# generated by tools/build_psx_exe.py from analysis/functions.json"]
    for r in census["functions"]:
        if r["space"] == "resident" and r["name"]:
            lines.append(f".equ {r['name']}, {r['start']}")
    inc = BUILD / "census_symbols.inc"
    inc.write_text("\n".join(lines) + "\n")
    return inc


def main() -> int:
    seg = load_segments()
    BUILD.mkdir(parents=True, exist_ok=True)
    write_symbols_inc()
    img = bytearray(original_exe(seg))

    manifest = {"image": seg["image"], "original_sha1": seg["sha1"], "attempted": []}
    for a in seg["attempted"]:
        want = a["end"] - a["start"]
        lang = "c" if (ROOT / a["source"]).suffix == ".c" else "asm"
        data = build_entry(a, seg, include_dirs=[BUILD, HANDWRITTEN])
        if isinstance(data, dict):
            section_results = []
            for section_name, section in a["sections"].items():
                section_data = data.get(section_name, b"")
                section_want = section["end"] - section["start"]
                if len(section_data) != section_want:
                    raise SystemExit(
                        f"{a['source']}:{section_name}: built {len(section_data)} bytes, "
                        f"layout range is {section_want} "
                        f"({section['start']:#x}..{section['end']:#x})")
                off = va_to_off(seg, section["start"])
                matched = bytes(img[off:off + section_want]) == section_data
                img[off:off + section_want] = section_data
                section_results.append({
                    "name": section_name,
                    "start": f"{section['start']:#010x}",
                    "end": f"{section['end']:#010x}",
                    "bytes": section_want,
                    "matches_original": matched,
                })
                print(f"[build] {a['source']}:{section_name} @ {section['start']:#x} "
                      f"({section_want} B, {lang}) {'MATCH' if matched else 'DIFFERS'}")
            manifest["attempted"].append({
                "start": f"{a['start']:#010x}", "end": f"{a['end']:#010x}",
                "source": a["source"], "language": lang,
                "declaration_profile": a.get("declaration_profile", "source"),
                "sections": section_results,
                "matches_original": all(s["matches_original"] for s in section_results),
            })
            continue
        if len(data) != want:
            raise SystemExit(f"{a['source']}: built {len(data)} bytes, census range is "
                             f"{want} ({a['start']:#x}..{a['end']:#x})")
        off = va_to_off(seg, a["start"])
        matched = bytes(img[off:off + want]) == data
        img[off:off + want] = data
        manifest["attempted"].append({
            "start": f"{a['start']:#010x}", "end": f"{a['end']:#010x}",
            "source": a["source"], "language": lang, "bytes": want,
            "declaration_profile": a.get("declaration_profile", "source"),
            "matches_original": matched})
        print(f"[build] {a['source']} @ {a['start']:#x} ({want} B, {lang}) "
              f"{'MATCH' if matched else 'DIFFERS'}")

    out = BUILD / f"{seg['image']}.rebuilt"
    out.write_bytes(img)
    manifest["rebuilt_sha1"] = sha1(bytes(img))
    (BUILD / "build_manifest.json").write_text(json.dumps(manifest, indent=2))
    print(f"[build] {out} sha1={manifest['rebuilt_sha1']} "
          f"({len(seg['attempted'])} function(s) from source)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
